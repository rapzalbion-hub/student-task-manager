CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('admin','dosen','mahasiswa')),
  username VARCHAR(50) UNIQUE,
  name VARCHAR(150) NOT NULL,
  nim VARCHAR(30) UNIQUE,
  nip VARCHAR(30) UNIQUE,
  email VARCHAR(150) UNIQUE,
  birth_date DATE,
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  password_hash VARCHAR(255) NOT NULL,
  class_name VARCHAR(30),
  study_program VARCHAR(100),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','pending')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE courses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) UNIQUE NOT NULL,
  name VARCHAR(150) NOT NULL,
  lecturer_id INTEGER NOT NULL REFERENCES users(id),
  semester SMALLINT NOT NULL CHECK (semester BETWEEN 1 AND 14),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX courses_lecturer_id_idx ON courses(lecturer_id);

CREATE TABLE tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lecturer_id INTEGER NOT NULL REFERENCES users(id),
  course_id INTEGER NOT NULL REFERENCES courses(id),
  code VARCHAR(30) UNIQUE NOT NULL,
  title VARCHAR(200) NOT NULL,
  description TEXT,
  task_type TEXT NOT NULL CHECK (task_type IN ('individu','kelompok')),
  assessment_type TEXT NOT NULL CHECK (assessment_type IN ('project','quiz','laporan','presentasi','lainnya')),
  deadline TIMESTAMP NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','closed')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX tasks_lecturer_id_idx ON tasks(lecturer_id);
CREATE INDEX tasks_course_id_idx ON tasks(course_id);

CREATE TABLE task_students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id INTEGER NOT NULL REFERENCES tasks(id),
  student_id INTEGER NOT NULL REFERENCES users(id),
  progress SMALLINT NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
  status TEXT NOT NULL DEFAULT 'not_started' CHECK (status IN ('not_started','in_progress','completed')),
  notes TEXT,
  claimed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(task_id,student_id)
);
CREATE INDEX task_students_student_id_idx ON task_students(student_id);

CREATE TABLE subtasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_student_id INTEGER NOT NULL REFERENCES task_students(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  is_completed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX subtasks_task_student_id_idx ON subtasks(task_student_id);

CREATE TABLE task_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_student_id INTEGER UNIQUE NOT NULL REFERENCES task_students(id),
  submitted_at TIMESTAMP NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('submitted','late','graded')),
  grade SMALLINT CHECK (grade BETWEEN 0 AND 100),
  feedback TEXT,
  graded_at TIMESTAMP
);

CREATE TABLE submission_files (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id INTEGER NOT NULL REFERENCES task_submissions(id) ON DELETE CASCADE,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  file_type VARCHAR(100) NOT NULL,
  file_size INTEGER NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX submission_files_submission_id_idx ON submission_files(submission_id);

CREATE TABLE attachments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  file_type VARCHAR(100) NOT NULL,
  file_size INTEGER NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX attachments_task_id_idx ON attachments(task_id);

CREATE TABLE notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  type VARCHAR(50) NOT NULL,
  message VARCHAR(255) NOT NULL,
  link VARCHAR(255),
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX notifications_user_id_idx ON notifications(user_id);

CREATE TABLE activity_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(100) NOT NULL,
  description VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX activity_logs_user_id_idx ON activity_logs(user_id);

CREATE TABLE login_attempts (
  identity_hash CHAR(64) PRIMARY KEY,
  window_started_at TIMESTAMP(3) NOT NULL,
  attempts SMALLINT NOT NULL
);
CREATE INDEX login_attempts_window_started_at_idx ON login_attempts(window_started_at);

CREATE FUNCTION update_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION update_updated_at();
CREATE TRIGGER tasks_updated_at BEFORE UPDATE ON tasks FOR EACH ROW EXECUTE FUNCTION update_updated_at();
